export const TEMPLATE_MAP = new Map(TEMPLATES.map((t) => [t.id, t]));

export const DEFAULT_TEMPLATE_ID = "classic";

/** 取模板；未知 id 兜底到 classic（与旧的 asTemplateId 行为一致） */
export function getTemplate(id: string): TemplateDef {
  return TEMPLATE_MAP.get(id) ?? TEMPLATE_MAP.get(DEFAULT_TEMPLATE_ID)!;
}

export function isTemplateId(id: string): boolean {
  return TEMPLATE_MAP.has(id);
}

/** 按骨架分组，供画廊做统计展示 */
export function countByLayout(): Record<LayoutKind, number> {
  const out = {} as Record<LayoutKind, number>;
  for (const t of TEMPLATES) {
    out[t.layout] = (out[t.layout] ?? 0) + 1;
  }
  return out;
}
